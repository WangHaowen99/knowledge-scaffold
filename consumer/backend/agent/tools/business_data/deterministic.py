"""Automatically derive Neo4j bindings for deterministic handlers.

The provider configuration stores connection and graph-scope information only.
Deterministic execution derives its runtime binding from that configuration, so
operators do not have to maintain a second set of snapshot-attestation fields.
The execution broker remains the enforcement point for read-only, allow-listed
graph operations.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any, Optional

from agent.tools.business_data.endpoint_security import (
    endpoint_has_forbidden_auth_material,
)
from agent.tools.business_data.providers.graph.scope import (
    GraphScopeError,
    build_graph_scope,
)
from agent.tools.business_data.provider_registry import (
    LEGACY_PROVIDER_ATTESTATION_FIELDS,
)
from agent.tools.business_data.resolver import (
    BusinessDataConnectionError,
    resolve_business_data_source,
)
from integration.sandbox.data_proxy import sandbox_reachable_url
from integration.sandbox.errors import SandboxUnavailableError
from ontology.operation_execution import canonical_json_bytes, sha256_bytes
from shared_capabilities.business_data import AuthSpec, EffectiveConnection


class DeterministicProviderError(ValueError):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


MIN_DETERMINISTIC_PROVIDER_SECRET_LENGTH = 8
_AUTO_BINDING_PROTOCOL = "neo4j-deterministic-binding-v1"
_SECRET_CONFIG_FIELDS = frozenset({"token", "username", "password"})
_NON_OPTION_CONFIG_FIELDS = (
    frozenset({"url", "uri"})
    | _SECRET_CONFIG_FIELDS
    | LEGACY_PROVIDER_ATTESTATION_FIELDS
)


@dataclass(frozen=True)
class DeterministicProviderBinding:
    provider: str
    source_ref: str
    data_revision: str
    scope_digest: str
    network_endpoint: str
    effective_connection: EffectiveConnection


def resolve_deterministic_provider_binding(
    *,
    workspace_id: Optional[str],
    ontology_id: str,
    ontology_version: str,
) -> DeterministicProviderBinding:
    """Build a run-scoped binding from the active Neo4j source.

    ``data_revision`` identifies the concrete Neo4j endpoint/database and
    ``scope_digest`` additionally binds the workspace, ontology and effective
    connection options.  Both values are generated by the backend and never
    come from user-editable snapshot metadata.
    """
    workspace = str(workspace_id or "").strip()
    ontology = str(ontology_id or "").strip()
    if not workspace or not ontology:
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Deterministic workspace provider requires workspace and ontology.",
        )

    try:
        source = resolve_business_data_source(
            workspace_id=workspace,
            ontology_id=ontology,
        )
    except BusinessDataConnectionError as exc:
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Deterministic provider is not configured.",
        ) from exc

    provider = str(source.provider or "").strip().casefold()
    # Neo4j is the only provider whose deterministic broker contract is
    # supported.  HugeGraph and model-backed providers stay on ordinary search.
    if provider != "neo4j":
        raise DeterministicProviderError(
            "provider_not_deterministic",
            "Provider '{}' does not support deterministic execution.".format(provider),
        )

    config = {
        key: value
        for key, value in dict(source.config or {}).items()
        if key not in LEGACY_PROVIDER_ATTESTATION_FIELDS
    }
    scope_config = _scope_config(
        config,
        workspace_id=workspace,
        ontology_id=ontology,
    )
    try:
        graph_scope = build_graph_scope(scope_config)
    except (GraphScopeError, TypeError, ValueError) as exc:
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Neo4j workspace/ontology scope is invalid.",
        ) from exc
    if not graph_scope.ontology_property or not graph_scope.ontology_value:
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Neo4j deterministic execution requires ontology isolation.",
        )

    database = str(config.get("database") or "neo4j").strip()
    if not database:
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Neo4j database is required.",
        )
    scope = {
        "workspace_id": workspace,
        "ontology_id": ontology,
        "ontology_version": str(ontology_version or "").strip(),
        "provider": provider,
        "database": database,
        "workspace_property": graph_scope.workspace_property,
        "workspace_value": graph_scope.workspace_value,
        "ontology_property": graph_scope.ontology_property,
        "ontology_value": graph_scope.ontology_value,
    }
    connection = _build_deterministic_effective_connection(
        config=config,
        scope=scope,
    )
    try:
        network_endpoint = sandbox_reachable_url(connection.endpoint)
    except (OSError, SandboxUnavailableError, ValueError) as exc:
        raise DeterministicProviderError(
            "provider_endpoint_unresolved",
            "Deterministic provider endpoint could not be resolved safely.",
        ) from exc

    for candidate in (connection.auth.token, connection.auth.password):
        if candidate and len(candidate) < MIN_DETERMINISTIC_PROVIDER_SECRET_LENGTH:
            raise DeterministicProviderError(
                "provider_credentials_unsafe",
                "Deterministic provider credentials do not meet the minimum length.",
            )

    physical_identity = {
        "protocol": _AUTO_BINDING_PROTOCOL,
        "provider": provider,
        "endpoint": connection.endpoint,
        "network_endpoint": network_endpoint,
        "database": database,
        "auth_username": connection.auth.username,
    }
    scope_identity = {
        **physical_identity,
        "workspace_id": workspace,
        "ontology_id": ontology,
        "ontology_version": str(ontology_version or "").strip(),
        "workspace_property": graph_scope.workspace_property,
        "workspace_value": graph_scope.workspace_value,
        "ontology_property": graph_scope.ontology_property,
        "ontology_value": graph_scope.ontology_value,
        "auth_type": connection.auth.type,
        "auth_username": connection.auth.username,
        "options": connection.options,
    }
    return DeterministicProviderBinding(
        provider=provider,
        source_ref="business_data",
        data_revision=sha256_bytes(canonical_json_bytes(physical_identity)),
        scope_digest=sha256_bytes(canonical_json_bytes(scope_identity)),
        network_endpoint=network_endpoint,
        effective_connection=connection,
    )


def _scope_config(
    config: Mapping[str, Any],
    *,
    workspace_id: str,
    ontology_id: str,
) -> dict[str, Any]:
    """Overlay runtime scope while preserving explicit provider choices."""
    values = dict(config)
    values["workspace_id"] = workspace_id
    values["ontology_id"] = ontology_id
    values["workspace_value"] = str(values.get("workspace_value") or "").strip() or workspace_id
    if "workspace_property" not in values:
        values["workspace_property"] = "d2o_workspace_id"
    # The registry supplies this default for persisted sources.  Applying it
    # here as well keeps the resolver safe for older/hand-built source objects.
    if "ontology_property" not in values:
        values["ontology_property"] = "d2o_ontology_id"
    if str(values.get("ontology_property") or "").strip():
        values["ontology_value"] = str(values.get("ontology_value") or "").strip() or ontology_id
    else:
        values["ontology_value"] = ""
    return values


def _build_deterministic_effective_connection(
    *,
    config: Mapping[str, Any],
    scope: Mapping[str, Any],
) -> EffectiveConnection:
    """Build the credential-bearing Neo4j connection used by the broker."""
    options = {
        key: value
        for key, value in dict(config).items()
        if key not in _NON_OPTION_CONFIG_FIELDS
    }
    options.update(scope)

    username = str(config.get("username") or "").strip()
    password = str(config.get("password") or "")
    token = str(config.get("token") or "").strip()
    if token:
        auth = AuthSpec(type="bearer", token=token)
    elif username or password:
        auth = AuthSpec(
            type="mindsdb_password",
            username=username,
            password=password,
        )
    else:
        auth = AuthSpec(type="none")

    endpoint = str(config.get("uri") or "").strip().rstrip("/")
    if not endpoint:
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Neo4j URI is required.",
        )
    if endpoint_has_forbidden_auth_material(endpoint):
        raise DeterministicProviderError(
            "provider_scope_invalid",
            "Neo4j credentials must use dedicated auth fields and URI fragments are forbidden.",
        )
    return EffectiveConnection(
        version=1,
        provider="neo4j",
        endpoint=endpoint,
        auth=auth,
        options=options,
    )
