"""Workspace/owner-scoped durable storage for candidate-set artifacts."""

from __future__ import annotations

import hashlib
import json
import logging
import os
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from utils.atomic_files import staged_bytes
from utils.identifiers import validate_session_id
from workspace.workspaces import get_workspace_paths

from .contracts import CandidateSet, SolverContractError
from .run_ledger import RunLedgerError, SolverRunLedger

logger = logging.getLogger(__name__)


class CandidateSetStoreError(ValueError):
    """Raised when a candidate-set artifact cannot be read or written."""


class CandidateSetNotFoundError(CandidateSetStoreError):
    """Missing or unauthorized artifacts are intentionally indistinguishable."""


class CandidateSetArtifactIntegrityError(CandidateSetStoreError):
    """Raised when an artifact exists but fails its immutable-content checks."""


class CandidateSetStore:
    """Persist immutable candidate sets below an owner namespace.

    The public reference is derived from the candidate-set digest rather than
    a random UUID.  Owner namespaces remain separate on disk, so equal content
    generated by two identities cannot grant either identity access to the
    other's artifact.
    """

    _DIGEST_HEX = re.compile(r"^[0-9a-f]{64}$")

    def __init__(self, workspace_id: str, *, ledger: SolverRunLedger | None = None) -> None:
        self.workspace_id = workspace_id
        paths = get_workspace_paths(workspace_id)
        self._runtime_root = paths.runtime_dir
        self._root = self._runtime_root / "solver_coordination" / "candidate_sets"
        self._root.mkdir(parents=True, exist_ok=True)
        self._ledger = ledger or SolverRunLedger(workspace_id)

    @staticmethod
    def _owner_namespace(owner_id: str) -> str:
        return hashlib.sha256(owner_id.encode("utf-8")).hexdigest()

    @classmethod
    def _digest_suffix(cls, digest: object) -> str:
        raw = str(digest or "")
        suffix = raw.rsplit(":", 1)[-1].lower()
        if cls._DIGEST_HEX.fullmatch(suffix):
            return suffix
        # A future digest algorithm may not expose a 64-character hex suffix;
        # hash the complete versioned digest to retain content addressing.
        return hashlib.sha256(raw.encode("utf-8")).hexdigest()

    def _path_for_ref(self, candidate_set_ref: str, *, owner_id: str) -> Path:
        try:
            normalized_ref = validate_session_id(candidate_set_ref)
        except ValueError as exc:
            raise CandidateSetNotFoundError("candidate set artifact not found") from exc
        if not normalized_ref.startswith("candidate_set_"):
            raise CandidateSetNotFoundError("candidate set artifact not found")
        suffix = normalized_ref.removeprefix("candidate_set_")
        if not self._DIGEST_HEX.fullmatch(suffix):
            raise CandidateSetNotFoundError("candidate set artifact not found")
        owner = str(owner_id or "").strip()
        if not owner:
            raise CandidateSetStoreError("owner_id is required")
        owner_root = self._root / self._owner_namespace(owner)
        target = (owner_root / (normalized_ref + ".json")).resolve()
        try:
            target.relative_to(self._root.resolve())
        except ValueError as exc:
            raise CandidateSetNotFoundError("candidate set artifact not found") from exc
        return target

    def put(self, candidate_set: CandidateSet, *, owner_id: str) -> tuple[str, dict[str, Any]]:
        owner = str(owner_id or "").strip()
        if not owner:
            raise CandidateSetStoreError("owner_id is required")
        if not isinstance(candidate_set, CandidateSet):
            raise CandidateSetStoreError("candidate_set must be a CandidateSet")
        candidate_set_ref = "candidate_set_{}".format(
            self._digest_suffix(candidate_set.candidate_set_digest)
        )
        payload = candidate_set.to_dict()
        payload.update(
            {
                "schema_version": "solver_coordination.v1",
                "artifact_type": "candidate_set",
                "candidate_set_ref": candidate_set_ref,
                "workspace_id": self.workspace_id,
                "owner_id": owner,
                "created_at": datetime.now(timezone.utc).isoformat(),
            }
        )
        target = self._path_for_ref(candidate_set_ref, owner_id=owner)
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            encoded = json.dumps(
                payload,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")
            with staged_bytes(
                directory=target.parent,
                prefix=".candidate-",
                suffix=".tmp",
                payload=encoded,
            ) as temporary:
                # Re-read and verify the staged bytes before they become visible.
                staged = self._read_payload(temporary)
                CandidateSet.from_dict(staged)
                if staged.get("candidate_set_ref") != candidate_set_ref:
                    raise CandidateSetArtifactIntegrityError(
                        "candidate set staged reference does not match digest"
                    )
                # Existing content must match the immutable payload. The
                # creation timestamp is envelope metadata, not identity.
                if target.exists():
                    existing = self._read_payload(target)
                    comparable_existing = dict(existing)
                    comparable_payload = dict(payload)
                    comparable_existing.pop("created_at", None)
                    comparable_payload.pop("created_at", None)
                    if comparable_existing != comparable_payload:
                        raise CandidateSetArtifactIntegrityError(
                            "candidate set digest is already bound to different content"
                        )
                else:
                    temporary.replace(target)
                    self._fsync_directory(target.parent)
        except Exception as exc:
            if isinstance(exc, CandidateSetStoreError):
                raise
            raise CandidateSetStoreError("failed to persist candidate set") from exc

        relative_path = target.relative_to(self._runtime_root).as_posix()
        try:
            self._ledger.register_artifact(
                artifact_digest=candidate_set.candidate_set_digest,
                artifact_type="candidate_set",
                artifact_ref=candidate_set_ref,
                artifact_path=relative_path,
                owner_id=owner,
                source_run_id=str(payload.get("source_run_id") or candidate_set.source_run_id),
            )
        except RunLedgerError as exc:
            raise CandidateSetStoreError("failed to register candidate set artifact") from exc
        return candidate_set_ref, payload

    @staticmethod
    def _fsync_directory(directory: Path) -> None:
        """Best-effort directory durability after an atomic rename."""

        try:
            fd = os.open(str(directory), os.O_RDONLY)
        except OSError:
            # Windows does not expose openable directory handles in all
            # supported configurations; the file fsync above remains the
            # portable guarantee there.
            return
        try:
            os.fsync(fd)
        except OSError:
            logger.debug("Candidate store directory fsync failed")
        finally:
            os.close(fd)

    @staticmethod
    def _read_payload(target: Path) -> dict[str, Any]:
        try:
            with target.open("r", encoding="utf-8") as handle:
                payload = json.load(handle)
        except (json.JSONDecodeError, OSError) as exc:
            raise CandidateSetArtifactIntegrityError("candidate set artifact integrity check failed") from exc
        if not isinstance(payload, dict):
            raise CandidateSetArtifactIntegrityError("candidate set artifact integrity check failed")
        return payload

    def get(
        self,
        candidate_set_ref: str,
        *,
        owner_id: str,
    ) -> CandidateSet:
        owner = str(owner_id or "").strip()
        if not owner:
            raise CandidateSetStoreError("owner_id is required")
        target = self._path_for_ref(candidate_set_ref, owner_id=owner)
        if not target.is_file():
            raise CandidateSetNotFoundError("candidate set artifact not found")
        payload = self._read_payload(target)
        if payload.get("workspace_id") != self.workspace_id or payload.get("owner_id") != owner:
            raise CandidateSetNotFoundError("candidate set artifact not found")
        if payload.get("candidate_set_ref") != candidate_set_ref:
            raise CandidateSetArtifactIntegrityError("candidate set artifact integrity check failed")
        if payload.get("artifact_type") != "candidate_set" or payload.get("schema_version") != "solver_coordination.v1":
            raise CandidateSetArtifactIntegrityError("candidate set artifact schema is invalid")

        try:
            candidate_set = CandidateSet.from_dict(payload)
        except SolverContractError as exc:
            raise CandidateSetArtifactIntegrityError("candidate set artifact integrity check failed") from exc
        expected_ref = "candidate_set_{}".format(self._digest_suffix(candidate_set.candidate_set_digest))
        if expected_ref != candidate_set_ref:
            raise CandidateSetArtifactIntegrityError("candidate set artifact reference does not match digest")
        return candidate_set
