"""Regenerate app/services/consumer_package_rules/ from a consumer upstream export.

The modeling service checks a package with the consumer's own import rules before publishing it.
The two codebases live in separate repositories, so the rules are copied here and synchronized by
hand: export the upstream ``common`` branch (``git archive``), run this script against the
directory that contains ``consumer/`` and ``plugins/``, review the diff, and run the rule tests,
including tests/test_consumer_rules_parity.py with CONSUMER_UPSTREAM_ROOT set to the same directory.

Only the definitions reachable from each spec's entry points are copied, with bodies unchanged;
imports of upstream modules are rewritten to the local copies, and any upstream import left
unmapped stops the script.

    python scripts/sync_consumer_package_rules.py --upstream <export dir> --commit <upstream commit>
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import logging
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / 'app' / 'services' / 'consumer_package_rules'
logger = logging.getLogger(__name__)
GENERATED_NOTE = ('# Generated by scripts/sync_consumer_package_rules.py from {source} in the consumer upstream;'
                  ' do not edit by hand.')
UPSTREAM_PACKAGES = ('ontology', 'config', 'plugin_api', 'solver_coordination', 'api', 'agent', 'integration',
                     'workspace', 'utils', 'shared_capabilities', 'persistence', 'llm')
MODULES = {
    'ontology.package_snapshot': '.package_snapshot',
    'ontology.package_validation': '.package_validation',
    'ontology.package_import': '.package_import',
    'ontology.ontologies': '.ontologies',
    'ontology.ontology_catalog': '.ontology_catalog',
    # The plugin facade forwards to the consumer's validator, which lives in package_validation.
    'plugin_api.packages': '.package_validation',
    'config': '.limits',
}


class SyncError(RuntimeError):
    """Upstream code the script cannot copy faithfully; nothing should be written from it."""


@dataclass(frozen=True)
class Spec:
    output: str
    source: str
    entries: tuple[str, ...]
    drop_members: dict[str, tuple[str, ...]] = field(default_factory=dict)
    overrides: dict[str, str] = field(default_factory=dict)
    extra_imports: tuple[str, ...] = ()


SPECS = (
    Spec('package_snapshot.py', 'consumer/backend/ontology/package_snapshot.py',
         ('PackageReadSession', 'PackageContentChangedError', 'read_package_bytes'),
         drop_members={'PackageReadSession': ('from_snapshot', 'snapshot')}),
    Spec('package_validation.py', 'consumer/backend/ontology/package_validation.py',
         ('SUPPORTED_ONTOLOGY_SCHEMA_VERSIONS', 'validate_no_runtime_binding_data', 'validate_ontology_revision',
          'reject_package_links', 'validate_ontology_tree_limits', 'validate_imported_object_aliases',
          'validate_imported_field_aliases')),
    Spec('package_import.py', 'consumer/backend/ontology/package_import.py',
         ('SUPPORTED_IMPORT_MANIFEST_KINDS', 'ImportableOntologyPackage', 'inspect_importable_package',
          'has_importable_package_layout')),
    Spec('ontologies.py', 'consumer/backend/ontology/ontologies.py', ('is_valid_ontology_version',)),
    Spec('ontology_catalog.py', 'consumer/backend/ontology/ontology_catalog.py',
         ('validate_object_aliases', 'validate_field_aliases', 'load_object_data_mappings',
          'validate_object_data_mappings', 'validate_value_bindings', 'ObjectAliasValidationResult',
          'FieldAliasValidationResult')),
    Spec('archive.py', 'consumer/backend/api/routes/ontologies.py',
         ('ONTOLOGY_MAX_ZIP_BYTES', 'OntologyImportError', '_safe_extract_zip', '_find_converted_ontology_root',
          '_is_valid_ontology_id'),
         overrides={'logger': 'logger = logging.getLogger(__name__)'}, extra_imports=('import logging',)),
    Spec('solver_layout.py', 'plugins/solver/backend/solver_coordination/package/layout.py',
         # The security error subclass is copied with the layout checks that raise it.
         ('SolverPackageLayoutError', 'SolverLayoutInspection', 'inspect_solver_package_layout',
          'validate_solver_package_layout')),
    Spec('solver_capability_catalog.py', 'plugins/solver/backend/solver_coordination/capability_catalog.py',
         ('declares_solver_layout', '_is_enabled')),
)


def _bound(alias: ast.alias) -> str:
    return alias.asname or alias.name.split('.')[0]


def _start(node: ast.AST, lines: list[str]) -> int:
    """First line of a definition, including decorators and the comment block right above it."""
    start = min([d.lineno for d in getattr(node, 'decorator_list', [])] + [node.lineno])
    while start > 1 and lines[start - 2].strip().startswith('#'):
        start -= 1
    return start


def _names(node: ast.AST, skip: tuple[ast.AST, ...] = ()) -> set[str]:
    found: set[str] = set()
    stack = [node]
    while stack:
        current = stack.pop()
        if current in skip:
            continue
        if isinstance(current, ast.Name):
            found.add(current.id)
        stack.extend(ast.iter_child_nodes(current))
    return found


def _rewrite_module(module: str) -> str | None:
    if module in MODULES:
        return MODULES[module]
    if module.split('.')[0] in UPSTREAM_PACKAGES:
        return None
    return module


def _import_text(node: ast.Import | ast.ImportFrom, used: set[str], indent: str = '') -> str:
    aliases = [a for a in node.names if _bound(a) in used]
    if isinstance(node, ast.ImportFrom) and node.module == '__future__':
        return indent + ast.unparse(node)
    if not aliases:
        return ''
    if isinstance(node, ast.Import):
        for alias in aliases:
            if _rewrite_module(alias.name) != alias.name:
                raise SyncError(f'unsupported upstream import: import {alias.name}')
        return indent + ast.unparse(ast.Import(names=aliases))
    if node.level:
        raise SyncError(f'unsupported relative import upstream: from {"." * node.level}{node.module or ""}')
    module = _rewrite_module(node.module or '')
    if module is None:
        raise SyncError(f'unmapped upstream import used by copied code: from {node.module} import ...')
    names = [ast.unparse(a) for a in aliases]
    line = f'{indent}from {module} import {", ".join(names)}'
    if len(line) <= 110:
        return line
    body = ''.join(f'{indent}    {name},\n' for name in names)
    return f'{indent}from {module} import (\n{body}{indent})'


def _rewrite_lazy_imports(text: str) -> str:
    for upstream, local in MODULES.items():
        text = re.sub(rf'(^\s*from ){re.escape(upstream)}( import )', rf'\g<1>{local}\g<2>', text, flags=re.M)
    leftover = re.search(r'^\s*(from|import) (' + '|'.join(UPSTREAM_PACKAGES) + r')\b', text, flags=re.M)
    if leftover:
        raise SyncError(f'unmapped upstream import inside copied code: {leftover.group(0).strip()}')
    return text


def trim(spec: Spec, source: str) -> tuple[str, list[str]]:
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    defs: dict[str, ast.AST] = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            defs[node.name] = node
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    defs[target.id] = node
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            defs[node.target.id] = node
    dropped: list[ast.AST] = []
    for owner, members in spec.drop_members.items():
        for member in defs[owner].body:
            if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef)) and member.name in members:
                dropped.append(member)
        if len([m for m in dropped if m in defs[owner].body]) != len(members):
            raise SyncError(f'{spec.output}: members to drop not found in {owner}')
    missing = [name for name in spec.entries if name not in defs]
    if missing:
        raise SyncError(f'{spec.output}: entry points not found upstream: {missing}')
    kept: dict[str, ast.AST] = {}
    stack = list(spec.entries)
    while stack:
        name = stack.pop()
        if name in kept or name not in defs or name in spec.overrides:
            continue
        kept[name] = defs[name]
        stack.extend(_names(defs[name], tuple(dropped)))
    nodes = sorted({id(node): node for node in kept.values()}.values(), key=lambda node: node.lineno)
    blocks = []
    for node in nodes:
        start, end = _start(node, lines), node.end_lineno
        cut = sorted((_start(m, lines), m.end_lineno) for m in dropped if node.lineno <= m.lineno <= end)
        text, cursor = '', start
        for cut_start, cut_end in cut:
            text += ''.join(lines[cursor - 1:cut_start - 1]).rstrip('\n') + '\n'
            cursor = cut_end + 1
        text += ''.join(lines[cursor - 1:end])
        blocks.append(text.rstrip('\n') + '\n')
    code = '\n\n'.join(blocks)
    used = set()
    for node in nodes:
        used |= _names(node, tuple(dropped))
    imports, type_checking = [], []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            text = _import_text(node, used)
            if text:
                imports.append(text)
        elif isinstance(node, ast.If) and ast.unparse(node.test) == 'TYPE_CHECKING':
            for inner in node.body:
                text = _import_text(inner, used, '    ')
                if text:
                    type_checking.append(text)
    if type_checking:
        if not any('TYPE_CHECKING' in line for line in imports):
            imports.append('from typing import TYPE_CHECKING')
        imports.append('if TYPE_CHECKING:\n' + '\n'.join(type_checking))
    header = [line for line in lines if line.startswith('# Copyright')][:1]
    docstring = ast.get_docstring(tree, clean=False)
    parts = [''.join(header) + GENERATED_NOTE.format(source=spec.source) + '\n']
    if docstring is not None:
        parts.append(f'"""{docstring}"""\n')
    parts.append('\n'.join(imports + list(spec.extra_imports)) + '\n')
    parts.append('\n'.join(spec.overrides.values()) + '\n' if spec.overrides else '')
    body = '\n'.join(part for part in parts if part) + '\n\n' + _rewrite_lazy_imports(code)
    compile(body, spec.output, 'exec')
    return body, sorted(kept)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--upstream', required=True, type=Path, help='directory containing consumer/ and plugins/')
    parser.add_argument('--commit', required=True, help='upstream commit the export was taken from')
    args = parser.parse_args()
    manifest = {'upstream_commit': args.commit, 'files': {}}
    for spec in SPECS:
        raw = (args.upstream / spec.source).read_bytes()
        text, kept = trim(spec, raw.decode('utf-8'))
        (TARGET / spec.output).write_text(text, encoding='utf-8')
        manifest['files'][spec.output] = {
            'source': spec.source, 'source_sha256': hashlib.sha256(raw).hexdigest(),
            'entries': list(spec.entries), 'copied_definitions': kept,
            'dropped_members': {k: list(v) for k, v in spec.drop_members.items()},
            'overridden': sorted(spec.overrides),
        }
        logger.info('%s: %d definitions from %s', spec.output, len(kept), spec.source)
    (TARGET / 'upstream.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def _configure_logging() -> None:
    """Progress goes to stdout through this script's own logger; the root logger is left alone."""
    handler = logging.StreamHandler(sys.stdout)
    handler.setFormatter(logging.Formatter('%(message)s'))
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)
    logger.propagate = False


if __name__ == '__main__':
    _configure_logging()
    try:
        main()
    except SyncError as error:
        sys.exit(str(error))
